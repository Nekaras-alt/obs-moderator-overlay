function detectLocale() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'ru' || saved === 'en') return saved
  } catch { /* ignore */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'en'
  return nav.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

const state = reactive({ locale: detectLocale() })

watch(() => state.locale, (v) => {
  try { localStorage.setItem(STORAGE_KEY, v) } catch { /* ignore */ }
  if (typeof document !== 'undefined') document.documentElement.lang = v
})

export function useI18n() {
  const locale = computed(() => state.locale)

  function t(key, vars) {
    const pack = messages[state.locale] || messages.en
    let out = pack[key] || messages.en[key] || key
    if (vars && typeof out === 'string') {
      for (const [k, v] of Object.entries(vars)) {
        out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v ?? ''))
      }
    }
    return out
  }

  function setLocale(code) {
    state.locale = code === 'ru' ? 'ru' : 'en'
  }

  return { locale, t, setLocale, messages }
}

